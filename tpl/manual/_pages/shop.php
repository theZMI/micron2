<h2>Модели и классы</h2>
<dl class="manual-defs">
    <dt><code>ShopProductModel</code></dt>
    <dd>Товар: артикул, название, цена и старая цена, описание, характеристики (JSON), картинки, группа вариантов, «покупают вместе», остаток. Поиск и фильтры - <code>search()</code>, варианты - <code>getVariants()</code>, <code>variantOptions()</code>.</dd>
    <dt><code>ShopOrderModel</code>, <code>ShopOrderItemModel</code></dt>
    <dd>Заказ и его позиции. Название и цена копируются из товара на момент заказа, поэтому старые заказы не меняются при правке товаров. Заказ реализует <code>IShopOrderModel</code> - интерфейс, через который с ним работает оплата.</dd>
    <dt><code>ShopCart</code></dt>
    <dd>Корзина в сессии: <code>add()</code>, <code>set()</code>, <code>remove()</code>, <code>count()</code>, <code>getItems()</code>, <code>summary()</code>.</dd>
    <dt><code>ShopFavorites</code></dt>
    <dd>Избранное: у гостя - в сессии, у пользователя - в БД; при входе переносится.</dd>
    <dt><code>ShopImage</code></dt>
    <dd>Картинки: при загрузке в админке уменьшаются до 1600px и превью 600px, лежат в <code>upl/shop/products/{id}/</code>.</dd>
    <dt><code>ShopRecentlyViewed</code>, <code>ShopProductImporter</code></dt>
    <dd>«Вы недавно смотрели» и импорт/выгрузка товаров.</dd>
</dl>
<p>Таблицы создаются сами при первом обращении к моделям.</p>

<h2>Варианты товара</h2>
<p>Если часы продаются в трёх цветах, а платье - в размерах S/M/L, то каждый вариант - отдельный товар со своим артикулом, ценой и остатком, но с одинаковым кодом в поле <code>variant_group</code>. На карточке появляется переключатель по характеристикам, которые у вариантов различаются:</p>
<ul>
    <li>«Цвет» показывается картинками (список таких характеристик - <code>variant_image_params</code>), остальное - кнопками;</li>
    <li>при смене цвета выбранный размер сохраняется;</li>
    <li>в каталоге у товара пишется «N вариантов».</li>
</ul>

<h2>«Покупают вместе»</h2>
<p>На странице товара и в корзине («Добавьте к заказу») показываются сначала товары, артикулы которых указаны в поле <code>related</code> (через запятую), а затем то, что реально покупали вместе в оплаченных заказах.</p>

<h2>Остатки</h2>
<p>Если у товара задан остаток (включён <code>track_stock</code>), то:</p>
<ul>
    <li>остаток списывается при создании заказа (с блокировкой строки - два покупателя не купят последний товар одновременно) и возвращается при отмене заказа;</li>
    <li>товар без остатка нельзя положить в корзину, в каталоге он показывается в конце, и есть фильтр «Только в наличии»;</li>
    <li>при малом остатке пишется «Осталось N шт.» (<code>low_stock</code>);</li>
    <li>брошенные неоплаченные заказы отменяет <code>/_cron/shop_cancel_unpaid</code> через <code>unpaid_order_ttl_hours</code> часов, и товар возвращается на склад.</li>
</ul>
<p>Пустой остаток - товар продаётся без учёта количества.</p>

