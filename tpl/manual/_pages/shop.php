<h2>Импорт и выгрузка товаров</h2>
<p>Товары можно вести в таблице. Админка «Магазин → Импорт товаров» загружает их из Google-таблицы (ссылка - <code>SHOP_IMPORT_GOOGLE_SHEET_URL</code> в <code>.env</code>, доступ «Все, у кого есть ссылка → Читатель») или из CSV-файла (подходит и Excel с разделителем <code>;</code>). По расписанию - <code>/_cron/shop_import</code>.</p>
<p>Первая строка таблицы - заголовки (можно по-английски или по-русски):</p>
<div class="manual-table-wrap">
<table>
    <tr><th>Колонка</th><th>Значение</th></tr>
    <tr><td><code>vendor_code</code> / Артикул</td><td>Обязательно. По нему товар находится при повторном импорте</td></tr>
    <tr><td><code>name</code> / Название</td><td>Обязательно</td></tr>
    <tr><td><code>price</code> / Цена</td><td>Обязательно</td></tr>
    <tr><td><code>price_old</code> / Старая цена</td><td>Зачёркнутая цена</td></tr>
    <tr><td><code>description</code> / Описание</td><td></td></tr>
    <tr><td><code>sort</code> / Порядок</td><td>Порядок в каталоге</td></tr>
    <tr><td><code>is_active</code> / В продаже</td><td></td></tr>
    <tr><td><code>variant_group</code> / Группа вариантов</td><td>Одинаковый код у вариантов одного товара</td></tr>
    <tr><td><code>related</code> / Покупают вместе</td><td>Артикулы через запятую</td></tr>
    <tr><td><code>stock</code> / Остаток</td><td>Пусто - не учитывать</td></tr>
    <tr><td><code>P: Название</code></td><td>Характеристики: <code>P: Цвет</code>, <code>P: Состав</code>, <code>P: Размер</code>...</td></tr>
</table>
</div>
<ul>
    <li>Товары, которых нет в таблице, снимаются с продажи (<code>hide_missing</code>).</li>
    <li>Если заголовки неправильные или нет ни одной правильной строки - каталог не меняется. Ошибочные строки пропускаются и перечисляются в отчёте.</li>
    <li>Кнопка «Выгрузить каталог (CSV)» (<code>/_admin/shop/export</code>) отдаёт весь каталог в этом же формате. Его можно загрузить в Google-таблицу и дальше вести там.</li>
</ul>

<h2>Админка магазина</h2>
<p>«Магазин → Товары» - товары с картинками, характеристиками, вариантами и остатками. «Магазин → Заказы» - смена статуса (при отмене остаток возвращается), платежи заказа и проверка оплаты в банке.</p>
<p>Об оплате и о том, как подключить свой тип заказа, - в разделе <a href="<?= $url('payments') ?>">Приём оплаты</a>.</p>
