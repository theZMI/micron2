<h1>Магазин</h1>
<p class="lead">В движок встроена готовая заготовка интернет-магазина: витрина с поиском и фильтрами, карточка товара с вариантами, корзина, избранное, оформление заказа без регистрации, оплата и управление в админке.</p>

