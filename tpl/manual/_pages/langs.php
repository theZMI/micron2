<h1>Мультиязычность</h1>
<p class="lead">Micron поддерживает несколько языков по каталоговой модели адресов: <code>site.ru/about</code> - язык по умолчанию, <code>site.ru/en/about</code> - английский. Для языка по умолчанию каталог не нужен, поэтому сначала можно сделать одну языковую версию.</p>

<h2>Настройка языков</h2>
<?= DocCode(<<<'CODE'
    <?php

    Config('langs', [
        'ru' => ['name' => 'Русский', 'abbr' => 'Рус', 'locale' => 'ru_RU'],
        'en' => ['name' => 'English', 'abbr' => 'Eng', 'locale' => 'en_US'],
        'uk' => ['name' => 'Українська', 'abbr' => 'Укр', 'locale' => 'uk_UA'], // Новый язык
    ]);

    const DEF_LANG = 'ru';
    CODE, 'php', 'core/config/languages.php') ?>
<p>Язык запроса движок определяет сам (константа <code>LANG</code>), а <code>SiteRoot()</code> добавляет его в ссылки, поэтому ссылки внутри английской версии остаются английскими.</p>

<h2>Языковые файлы</h2>
<p>Тексты страницы хранятся в <code>lang/язык/имя_компонента.php</code> и подключаются вместе с компонентом: сначала файл языка по умолчанию, затем текущего. Поэтому в файле другого языка достаточно перевести только часть текстов - остальное останется из языка по умолчанию.</p>
<?= DocCode(<<<'CODE'
    <?php

    $g_lang['m_title']       = 'Наши контакты';  // Заголовок страницы
    $g_lang['m_description'] = 'Адрес и телефоны компании';
    $g_lang['address']       = '<strong>ООО «Компания»</strong><br>Москва, ул. Пушкина, 1';
    $g_lang['send_btn__noTags'] = 'Отправить сообщение';
    CODE, 'php', 'lang/ru/contacts.php') ?>
<?= DocCode(<<<'CODE'
    <h1><?= L('m_title') ?></h1>
    <address><?= L('address') ?></address>
    <button class="btn btn-dark"><?= L('send_btn__noTags') ?></button>
    CODE, 'php', 'tpl/contacts.php') ?>
<p>Функция <code>L()</code> возвращает текст по ключу, а если его нет - сам ключ. Поэтому можно сразу писать <code>L('Hello world')</code>, а перевод добавить потом.</p>

<h2>Тексты для всех страниц</h2>
<p>Файлы из <code>lang/язык/_autoload/</code> загружаются при каждом запросе. Там лежат заголовок и описание сайта по умолчанию (<code>main.php</code>), телефон и почта поддержки (<code>contacts.php</code>), тексты ошибок загрузки файлов и т. д.</p>

<h2>Редактирование текстов в админке</h2>
<p>Раздел админки «Страницы» позволяет менять тексты языковых файлов без программиста. Для текстов с HTML показывается визуальный редактор (CKEditor), для простого текста - обычное поле.</p>
<p>Если в ключе есть <code>__noTags</code> (например, <code>send_btn__noTags</code>), редактор для него не показывается: так в заголовок <code>&lt;h1&gt;Контакты&lt;/h1&gt;</code> никогда не попадёт лишний <code>&lt;p&gt;</code>.</p>
<div class="manual-note">
    <p>Не кладите всю страницу в одну языковую переменную. Не все теги корректно редактируются в визуальном редакторе, а человек, который будет править текст, легко превратит <code>&lt;h1&gt;</code> в <code>&lt;p&gt;</code> с большим шрифтом. Заголовки и блоки со сложной разметкой (<code>&lt;address&gt;</code>, таблицы) лучше держать отдельно.</p>
</div>
<h2>Когда выносить тексты</h2>
<p>Если многоязычность и правка текстов через админку не нужны, тексты можно писать прямо в шаблонах. Выносить их в языковые файлы удобнее ближе к концу работы над проектом. Кодировка всех файлов - UTF-8.</p>
