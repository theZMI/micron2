<h2>Цели и задачи</h2>
<p>Возможно, вы замечали, что писать на большинстве известных фреймворков - это как писать на новом языке программирования: для всех функций есть «обёртки» и надстройки, а количество кода и его читабельность совсем не такие, какими хотелось бы их видеть. Поэтому приходится знать только основу и использовать функции фреймворка как чёрный ящик.</p>
<p>Нашей целью было сделать движок настолько маленьким и легко читаемым, насколько это возможно. Каждый желающий может скачать Micron и буквально за один вечер понять его устройство и принцип работы. Мы считаем, что такой движок лучше всего подходит начинающим программистам: он позволяет изучить основы построения веб-приложений и быстро влиться в команду разработчиков.</p>

<h2>Преимущества</h2>

<h3>HMVC (компонентная модель) - как модель построения страниц</h3>
<p>Каждый компонент может объявить свой собственный <code>&lt;head&gt;</code> (и <code>&lt;bottom&gt;</code>). Это позволяет избавиться от дублирования кода и делать компоненты максимально независимыми и переносимыми, подключая в них все нужные js, css и пр. без боязни дублирования.</p>

<h3>Лёгкий и читабельный код, разбитый на небольшие блоки</h3>
<p>Прозрачная архитектура позволяет менять и дописывать сам движок под конкретные нужды, а простота кода избавляет от необходимости лишний раз заглядывать в документацию.</p>

<h3>Работа с базами данных: DbSimple и модели</h3>
<p>Модели - сердцевина большинства сайтов. В Micron встроены DbSimple (безопасные плейсхолдеры в запросах) и простые модели в стиле ActiveRecord: <code>$user = new UserModel(1001); $user-&gt;name = 'Иван';</code>. Таблицы создаются сами, данные загружаются пачкой и лениво, изменения схемы - через <a href="<?= $url('migrations') ?>">миграции</a>.</p>

<h3>Мультиязычность (каталоговая модель адресов)</h3>
<p>Сайт может работать на нескольких языках: <code>site.ru/en/about</code>. Для языка по умолчанию каталог не нужен, поэтому можно сначала сделать только одну языковую версию.</p>

<h3>Роутинг и middleware</h3>
<p>Адрес <code>site.ru/contacts</code> по умолчанию подключает компонент <code>contacts</code>, а для особых разделов (админка, API, кабинет, cron) есть явные маршруты с middleware: проверка авторизации, подготовка API и пр.</p>

<h3>Сборка css/js: ExtraPacker и webpack</h3>
<p>ExtraPacker автоматически склеивает и сжимает css/less/js, подключённые в компонентах, а webpack собирает основной бандл сайта: Bootstrap 5, SCSS, TypeScript и Vue 3.</p>

<h3>Главный шаблон сайта как компонент</h3>
<p>Обычно все страницы выводятся внутри общего шаблона с одинаковыми шапкой и футером. Главный шаблон (<code>_main_tpl</code>) и его смена прямо из контроллера уже встроены в Micron.</p>

<h3>Простая и качественная отладка</h3>
<p>Debug-панель с запросами к БД и бенчмарком по каждому компоненту, перехват ошибок с полным backtrace, лог ошибок в админке и разделение режимов разработки и боевого сервера через <code>DEBUG_MODE</code> в <code>.env</code>.</p>

<h3>Высокая безопасность «по умолчанию»</h3>
<p>Вход пользователей без паролей - по одноразовому коду из письма, защита от CSRF и перебора кодов, HttpOnly-cookie, очистка входных данных в <code>Get()</code>/<code>Post()</code>, плейсхолдеры в запросах, служебные компоненты недоступны по url. Остальное - простые правила из раздела <a href="<?= $url('security') ?>">Безопасность</a>.</p>

<h3>Готовые модули</h3>
<p>Админка, кабинет пользователя, REST API с токенами, магазин, приём оплаты, уведомления (email, SMS, Telegram, push), импорт товаров из Google-таблиц, PWA и раздача мобильных приложений.</p>

<h3>Бесплатный и без ограничений</h3>
<p>Micron распространяется по лицензии WTFPL, которая не накладывает никаких ограничений на применение, копирование и изменение.</p>

