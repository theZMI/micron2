<h1>Админка</h1>
<p class="lead">Админка находится по адресу <code>/_admin</code>. У неё свой главный шаблон и свои склеенные css/js, а доступ только у авторизованных администраторов.</p>

<h2>Вход</h2>
<p>Первый админ создаётся из <code>ADMIN_DEFAULT_LOGIN</code> и <code>ADMIN_DEFAULT_PASSWORD</code> в <code>.env</code> - только если в БД ещё нет ни одного админа. Остальных админов можно завести в разделе «Для техников → Администраторы».</p>
<p>Если не получается войти, проверьте, что браузер сохраняет cookie. После 10 неудачных попыток на один логин или 30 с одного IP за 15 минут вход блокируется (настройки в <code>core/config/security.php</code>).</p>

<h2>Разделы</h2>
<dl class="manual-defs">
    <dt>Магазин</dt>
    <dd>Заказы (статус, платежи, проверка оплаты в банке), товары (характеристики, картинки, варианты, остатки), импорт товаров из Google-таблицы или CSV и выгрузка каталога.</dd>
    <dt>Пользователи</dt>
    <dd>Список и редактирование пользователей сайта.</dd>
    <dt>Страницы и «Новая страница»</dt>
    <dd>Редактирование текстов из языковых файлов (<code>lang/*</code>) с визуальным редактором CKEditor, заголовков и описаний страниц.</dd>
    <dt>Для техников</dt>
    <dd>Лог ошибок, администраторы, проверка отправки писем/SMS/push/Telegram, свободное место на сервере, бэкап БД, проверка зависших платежей, отмена брошенных заказов, информация о склеенных css/js, миграции БД и «Закрыть/открыть сайт» (показ страницы технических работ для всех, кроме админов).</dd>
</dl>

<h2>Свой раздел</h2>
<p>Страница админки - обычный компонент в <code>src/_admin</code> и <code>tpl/_admin</code>: <code>src/_admin/news.php</code> откроется по адресу <code>/_admin/news</code> и только для админа (это проверяет <code>AdminAuthMiddleware</code>). Пункт меню добавляется файлом настроек:</p>
