<h2>Защита</h2>
<ul>
    <li>Переходы в админку с чужих сайтов (ссылки вида <code>?a=delete</code>) не выполняют действие, а открывают главную админки.</li>
    <li>Изменяющие запросы (POST и пр.) с чужих сайтов отклоняются.</li>
    <li>Действия, которые что-то меняют, делайте только через POST-формы - смотрите <a href="<?= $url('security') ?>">Безопасность</a>.</li>
</ul>
