<h1>Безопасность</h1>
<p class="lead">Многое в Micron защищено по умолчанию, но главная защита - внимательность программиста. Ниже - что уже встроено и простые правила, которые стоит соблюдать.</p>

<h2>Что уже встроено</h2>
<ul>
    <li>У пользователей нет паролей: вход по одноразовому коду из письма (паролей, которые можно украсть или подобрать, просто нет). Пароли есть только у админов - через <code>password_hash()</code>. Сессии - случайные токены (в БД только sha256), cookie - HttpOnly и <code>SameSite=Lax</code>.</li>
    <li>CSRF: изменяющие запросы (POST и пр.) с чужих сайтов отклоняются (проверка <code>Sec-Fetch-Site</code>/<code>Origin</code>/<code>Referer</code>).</li>
    <li>Перебор: после 10 неудачных попыток на логин или 30 с одного IP за 15 минут вход блокируется; на каждый код - не больше 5 попыток.</li>
    <li>CORS: кросс-доменные запросы - только доменам из <code>CORS_ALLOWED_ORIGINS</code>.</li>
    <li>IP посетителя берётся из <code>REMOTE_ADDR</code>, а <code>X-Forwarded-For</code> учитывается только от прокси из <code>TRUSTED_PROXIES</code>.</li>
    <li>Редиректы «обратно» - только на страницы своего сайта (<code>SafeRedirectUrl()</code>).</li>
    <li>Служебные компоненты (<code>_*</code>) не открываются по адресу, имя компонента из адреса очищается от <code>../</code>.</li>
    <li>Снаружи недоступны <code>.env</code>, <code>composer.json</code>, логи в <code>tmp/</code>, <code>lib/</code>, <code>apps/</code>, <code>db_backups/</code>; в <code>upl/</code> и <code>tmp/</code> запрещён запуск скриптов.</li>
    <li>Заголовки <code>X-Frame-Options</code>, <code>X-Content-Type-Options</code>, <code>Referrer-Policy</code>.</li>
    <li>Капча и коды подтверждения одноразовые; в лог ошибок не попадают пароли, токены и cookie.</li>
</ul>

<h2>Всегда проверяйте данные от пользователя</h2>
<p>Преобразуйте их в минимально нужную величину и получайте через функции движка <code>Get()</code> и <code>Post()</code>. Они уже убирают XSS-вставки и экранируют HTML, но главной защитой остаются ум и профессионализм программиста. Большинство ошибок появляется именно из-за пренебрежения к входным данным. Несколько неправильных примеров получения номера страницы и правильный в конце:</p>
<?= DocCode(<<<'CODE'
    $page = Get('p', 1);              // Неверно - можно передать строку
    $page = intval(Get('p', 1));      // Неверно - возможны отрицательные числа
    $page = abs(intval(Get('p', 1))); // Неверно - можно получить 0, а страницы считаются от 1

    // Верно:
    $page = max(1, (int)Get('p', 1)); // Всегда целое число от 1
    CODE) ?>
<p>Ещё один вариант неправильной проверки:</p>
<?= DocCode(<<<'CODE'
    if ($n != (int)$n) {
        // Если в начале строки передать число, то проверка пройдёт
        // Пример: $n = "123' AND BENCHMARK(SIN(1), 100000000000000) --"
    }
    CODE) ?>
<p>Правильно - всегда спрашивать себя: «Какие значения может принимать эта переменная?» - и накладывать ограничения. Номер страницы - обязательно целое число больше нуля.</p>

<h2>Всегда используйте плейсхолдеры в запросах к БД</h2>
<p>Никогда не вставляйте данные в SQL склейкой строк - только <code>?</code>, <code>?d</code>, <code>?a</code>, <code>?#</code> (смотрите <a href="<?= $url('db') ?>">Работа с БД</a>).</p>

<h2>Экранируйте вывод</h2>
<p>Значения из <code>Get()</code>/<code>Post()</code> уже экранированы. Данные из БД, которые ввёл пользователь, выводите через <code>htmlspecialchars()</code>, если они не прошли через <code>Post()</code> при сохранении.</p>

<h2>Меняйте стандартные имена логов</h2>
<p>Задайте свои имена лог-файлов в <code>.env</code> (<code>ERROR_LOG_FILE</code>, <code>DATABASE_LOG_FILE</code>). Если этого не сделать, злоумышленник, изучив ошибки и структуру сайта, быстрее найдёт уязвимое место. Не выключайте логирование ошибок - взломать, не наследив, непросто.</p>

<h2>Не выводите ошибки на экран на боевом сервере</h2>
<p>Показ ошибок плохо сказывается на имидже сайта и открывает чужому глазу внутренние механизмы - причём именно те, что работают некорректно. На сервере - <code>DEBUG_MODE=0</code>. Хорошая практика - оформить компонент <code>500</code> под свой дизайн, чтобы у посетителя был понятный следующий шаг.</p>

<h2>Давайте всему и всем минимально возможные права</h2>
<h3>Права MySQL-пользователя</h3>
<p>Пусть есть два сайта: на одном проходят платежи (<code>payment.example.com</code>), а другой только выводит информацию из той же БД (<code>example.com</code>). Грамотно будет создать для второго отдельного MySQL-пользователя с правом только на <code>SELECT</code> - тогда даже ошибка программиста на <code>example.com</code> не навредит платёжной базе. Плюс - отдельная статистика запросов от каждого сайта.</p>
<h3>Права на файлы и папки</h3>
<p>Пусть вы написали код, который по ошибке складывает кеш не в <code>tmp</code>, а в <code>tpl</code>. Если запись разрешена только в <code>tmp</code> и <code>upl</code>, папка <code>tpl</code> не замусорится, а ошибку вы заметите сразу. Правило одно: всегда давайте минимально возможные права.</p>

<h2>Не храните пароли в открытом виде</h2>
<p>Пользователям Micron пароли вообще не нужны (вход по коду), но если вы храните пароли (как у админов) - храните только то, что нужно для проверки. Для паролей это хеш - и в Micron он делается через <code>password_hash()</code>/<code>password_verify()</code> (со своей солью для каждого пароля), а не через <code>md5</code>. Это относится и к другим данным: например, от номера карты можно хранить только начало и конец - для отображения пользователю.</p>

<h2>GET - для получения данных, POST - для действий</h2>
<p>Пусть голосование сделано по адресу <code>site.ru/comment?id=1001&amp;action=vote_plus</code>. Кто-то разместит эту ссылку на популярных сайтах (или в <code>&lt;img src&gt;</code>) и накрутит голоса. Или страница с AJAX-вызовами <code>/logout</code> разных сайтов разлогинит посетителя везде. Все действия, которые что-то меняют, - только через POST-формы. Micron дополнительно отклоняет POST с чужих сайтов.</p>

<h2>Не доверяйте данным, пришедшим от браузера</h2>
<p>Заголовки <code>HTTP_*</code> (<code>HTTP_REFERER</code>, <code>USER_AGENT</code>, <code>X-Forwarded-For</code>), mime-type загруженных файлов и пр. легко подделать:</p>
<?= DocCode(<<<'CODE'
    header('Location: ' . $_SERVER['HTTP_REFERER']); // Потенциально опасный код
    UrlRedirect::go(SafeRedirectUrl($_SERVER['HTTP_REFERER'] ?? '', SiteRoot())); // Безопасно
    CODE) ?>

<h2>Не полагайтесь на проверки в JavaScript</h2>
<p>Включённый JS - совсем не обязательное условие, а запрос можно отправить и без браузера. Сначала пишите проверку на сервере, а проверку на JS - как бонус для удобства.</p>

<h2>Оставляйте в прямом доступе минимум файлов</h2>
<p>Чем меньше файлов можно открыть по адресу, тем меньше простор для ошибок. В Micron все запросы идут через <code>index.php</code>, а <code>.htaccess</code> закрывает служебные файлы и папки.</p>

<h2>Не давайте загружать исполняемые файлы</h2>
<p>Представьте, что для аватарок не проверяется тип файла, и кто-то загрузил в <code>/upl</code> скрипт <code>delete_all.php</code>, а затем вызвал его по адресу. Проверяйте тип и расширение загружаемых файлов (<code>Uploader</code> делает это по настройкам) и не давайте пользователю самому называть файлы. В <code>upl/</code> запуск PHP запрещён, но рассчитывать только на это не стоит.</p>

<h2>Проверяйте имена подключаемых файлов</h2>
<p>Если имя файла приходит от пользователя, приведите его к безопасному виду (<code>FileSys::filenameSecurity()</code>) и проверьте, что итоговый путь внутри нужной папки. Иначе возможны запросы вида <code>?file=../../.env</code>.</p>

<h2>Ключи и пароли - только в .env</h2>
<p>Никогда не пишите пароли и ключи в коде и не добавляйте <code>.env</code> в git.</p>

<h2>Прочее</h2>
<ul>
    <li>Используйте SFTP/SSH вместо FTP.</li>
    <li>Регулярно проверяйте компьютер на вирусы и снифферы - они могут перехватывать доступы к серверу.</li>
    <li>Никогда не выключайте проверки в коде: исключения, <code>trigger_error</code>, проверки входных данных. Пара миллисекунд мифической экономии не стоит потерянной защиты.</li>
</ul>
